package com.nalin.urlshortener;

import com.nalin.urlshortener.dto.LoginRequest;
import com.nalin.urlshortener.dto.LoginResponse;
import com.nalin.urlshortener.dto.RegisterRequest;
import com.nalin.urlshortener.entity.User;
import com.nalin.urlshortener.repository.UserRepository;
import com.nalin.urlshortener.service.AuthService;
import com.nalin.urlshortener.service.JwtService;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.ArgumentCaptor;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.http.HttpStatus;
import org.springframework.security.crypto.bcrypt.BCryptPasswordEncoder;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.test.util.ReflectionTestUtils;
import org.springframework.web.server.ResponseStatusException;

import java.util.Optional;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.Mockito.*;

@ExtendWith(MockitoExtension.class)
class AuthServiceTest {
    @Mock
    private UserRepository userRepository;
    @Mock
    private JwtService jwtService;
    private final PasswordEncoder passwordEncoder = new BCryptPasswordEncoder();
    private AuthService authService;

    @BeforeEach
    void setUp() {
        authService = new AuthService(userRepository, passwordEncoder, jwtService);
    }

    @Test
    void register_passesAndSavesHashedPassword(){
        when(userRepository.existsByEmail("email@example.com")).thenReturn(false);

        authService.register(new RegisterRequest("  EMAIL@example.com  ", "password"));

        // Check save() was called and get the User passed to it
        ArgumentCaptor<User> argumentCaptor = ArgumentCaptor.forClass(User.class);
        verify(userRepository).save(argumentCaptor.capture());
        User savedUser = argumentCaptor.getValue();

        assertEquals("email@example.com", savedUser.getEmail()); // Saved as trimmed, lowercase
        assertNotEquals("password", savedUser.getPasswordHash());
        assertTrue(passwordEncoder.matches("password", savedUser.getPasswordHash()));
    }

    @Test
    void register_rejectsDuplicateEmail() {
        when(userRepository.existsByEmail("email@example.com")).thenReturn(true);

        ResponseStatusException ex = assertThrows(ResponseStatusException.class, () -> authService.register(new RegisterRequest("email@example.com", "password")));

        assertEquals(HttpStatus.CONFLICT, ex.getStatusCode());
        verify(userRepository, never()).save(any());
    }

    @Test
    void register_rejectsPasswordOver72Bytes() {
        String longThaiPassword = "ก".repeat(30);

        ResponseStatusException ex = assertThrows(ResponseStatusException.class, () -> authService.register(new RegisterRequest("email@example.com", longThaiPassword)));

        assertEquals(HttpStatus.BAD_REQUEST, ex.getStatusCode());
        assertEquals("Password is too long", ex.getReason());
        verify(userRepository, never()).save(any());
    }

    @Test
    void login_passesAndReturnsToken() {
        User user = new User("email@example.com", passwordEncoder.encode("password"));
        ReflectionTestUtils.setField(user, "id", 42L); // id is normally generated by PostgreSQL on register, but no real database here, set it manually

        when(userRepository.findByEmail("email@example.com")).thenReturn(Optional.of(user));
        when(jwtService.generateToken(42L)).thenReturn("example-token");

        LoginResponse response = authService.login(new LoginRequest("  EMAIL@example.com  ", "password"));

        assertEquals("example-token", response.token());
    }

    @Test
    void login_rejectsWrongPassword() {
        User user = new User("email@example.com", passwordEncoder.encode("password"));
        when(userRepository.findByEmail("email@example.com")).thenReturn(Optional.of(user));

        ResponseStatusException ex = assertThrows(ResponseStatusException.class, () -> authService.login(new LoginRequest("email@example.com", "wrongPassword")));

        assertEquals(HttpStatus.UNAUTHORIZED, ex.getStatusCode());
        assertEquals("Wrong email or password", ex.getReason());
        verify(jwtService, never()).generateToken(any());
    }

    @Test
    void login_rejectsUnknownEmail() {
        when(userRepository.findByEmail("unknown@example.com")).thenReturn(Optional.empty());

        ResponseStatusException ex = assertThrows(ResponseStatusException.class, () -> authService.login(new LoginRequest("unknown@example.com", "password")));

        assertEquals(HttpStatus.UNAUTHORIZED, ex.getStatusCode());
        assertEquals("Wrong email or password", ex.getReason());
        verify(jwtService, never()).generateToken(any());
    }
}
